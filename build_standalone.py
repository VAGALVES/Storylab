from pathlib import Path
import base64
r=Path(__file__).parent
html=(r/'index.html').read_text(encoding='utf-8')
css=(r/'style.css').read_text(encoding='utf-8')
data=(r/'data.js').read_text(encoding='utf-8')
app=(r/'app.js').read_text(encoding='utf-8')
atlas_data=(r/'atlas-data.js').read_text(encoding='utf-8')
urbanism_concepts=(r/'urbanism-concepts.js').read_text(encoding='utf-8')
urbanism_lexicon=(r/'urbanism-lexicon.js').read_text(encoding='utf-8')
urbanism_atlas=(r/'urbanism-atlas.js').read_text(encoding='utf-8')
atlas_engine=(r/'atlas-engine.js').read_text(encoding='utf-8')
atlas_recorder=(r/'atlas-recorder.js').read_text(encoding='utf-8')
atlas_audio=(r/'atlas-audio-ui.js').read_text(encoding='utf-8')
interact=(r/'interact.js').read_text(encoding='utf-8')
svg=(r/'assets/skyline.svg').read_bytes();icon=(r/'assets/icon.svg').read_bytes()
hero_data='data:image/svg+xml;base64,'+base64.b64encode(svg).decode()
icon_data='data:image/svg+xml;base64,'+base64.b64encode(icon).decode()
html=html.replace('<link rel="icon" href="assets/icon.svg" type="image/svg+xml">',f'<link rel="icon" href="{icon_data}" type="image/svg+xml">')
html=html.replace('<link rel="manifest" href="manifest.webmanifest">','')
html=html.replace('<link rel="stylesheet" href="style.css">','<style>\n'+css+'\n</style>')
html=html.replace('<script src="data.js"></script>','<script>\n'+data.replace('</script','<\\/script')+'\n</script>')
html=html.replace('<script src="atlas-data.js"></script>','<script>\n'+atlas_data+'\n</script>')
html=html.replace('<script src="urbanism-concepts.js"></script>','<script>\n'+urbanism_concepts+'\n</script>')
html=html.replace('<script src="urbanism-lexicon.js"></script>','<script>\n'+urbanism_lexicon+'\n</script>')
html=html.replace('<script src="urbanism-atlas.js"></script>','<script>\n'+urbanism_atlas+'\n</script>')
html=html.replace('<script src="atlas-engine.js"></script>','<script>\n'+atlas_engine+'\n</script>')
html=html.replace('<script src="atlas-recorder.js"></script>','<script>\n'+atlas_recorder+'\n</script>')
html=html.replace('<script src="atlas-audio-ui.js"></script>','<script>\n'+atlas_audio+'\n</script>')
html=html.replace('<script src="interact.js"></script>','<script>\n'+interact+'\n</script>')
html=html.replace('<script src="app.js"></script>','<script>\n'+app.replace('</script','<\\/script')+'\n</script>')
html=html.replace('src=\\"assets/skyline.svg\\"','src=\\"'+hero_data+'\\"')
html=html.replace('src="assets/skyline.svg"','src="'+hero_data+'"')
out=r/'storylab-shanghai-offline.html'
out.write_text(html,encoding='utf-8')
print('HTML único:',out)
