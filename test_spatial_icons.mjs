import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const read=p=>readFileSync(new URL(p,import.meta.url),'utf8');
const D=JSON.parse(read('content/storylab_data.json'));
const G=JSON.parse(read('content/atlas_guides.json'));
const w={STORYLAB_DATA:D,STORYLAB_ATLAS_GUIDES:G};
const listeners={};
const doc={addEventListener(k,fn){(listeners[k]??=[]).push(fn)},getElementById(){return null}};
const env=vm.createContext({window:w,document:doc,console});
const scripts=['urbanism-concepts.js','urbanism-lexicon.js','urbanism-atlas.js','spatial-verbs-data.js','spatial-regency-data.js','spatial-verb-icons.js','spatial-verbs.js'];
for(const p of scripts)vm.runInContext(read(p),env,{filename:p});
const lib=w.StoryLabVerbIcons,lab=w.StoryLabVerbLab;
const routes=['atravessar','cruzar','transpor','percorrer','desviar','serpentear','bifurcar-se','convergir'];
assert.equal(lib.keys().length,8,'oito diagramas únicos no primeiro campo');
const diagrams=new Set();
for(const verb of routes){
 assert.ok(lib.has(verb),verb);
 const model=w.STORYLAB_SPATIAL_VERB_DATA[3].verbs.find(v=>v.pt===verb);
 assert.equal(model.iconKey,verb,'a fonte editorial liga termo ao ícone específico');
 const svg=lib.render(model.iconKey,verb);
 const mini=lib.render(model.iconKey,verb,{mini:true});
 assert.match(svg,/<svg class="vl-diagram" role="img"/);
 assert.ok(svg.includes('aria-label="Diagrama do verbo '+verb+'"'));
 assert.match(mini,/<svg class="vl-mini-diagram" aria-hidden="true" focusable="false"/);
 assert.ok(!mini.includes('aria-label='));
 assert.ok(svg.includes('viewBox="0 0 260 115"'));
 assert.ok(!svg.includes('http://') || svg.includes('xmlns="http://www.w3.org/2000/svg"'));
 assert.ok(!svg.includes('<image')&&!svg.includes('<script')&&!svg.includes('<foreignObject'));
 assert.ok(svg.includes('vl-edge'));
 assert.ok(svg.includes('vl-stroke'),'setas / trajetos direcionais: '+verb);
 const drawing=svg.slice(svg.indexOf('</svg>')-100,svg.indexOf('</svg>'));
 assert.ok(drawing.length>10);
 diagrams.add(svg.replace('aria-label="Diagrama do verbo '+verb+'"','aria-label="diagram"'));
}
assert.equal(diagrams.size,8,'cada verbo requer geometria distinta');
const branch=lib.render('bifurcar-se','bifurcar-se');
const merge=lib.render('convergir','convergir');
const winding=lib.render('serpentear','serpentear');
assert.notEqual(branch,merge);
assert.ok(branch.includes('M111 58C')||branch.includes('M111 58'));
assert.ok(merge.includes('M30 24')&&merge.includes('M30 91'));
assert.ok(winding.includes('C49 13 71 101 96 57'));
assert.equal(lib.has('ladear'),false);
assert.equal(lib.render('ladear','ladear'),'');
const entries=lab.entries();
assert.equal(entries.length,64,'não altera quantidade do atlas nem domínio por termo');
assert.equal(D.atlas.length,62);
assert.equal(D.atlas.reduce((n,t)=>n+t.terms.length,0),717);
const g=entries.filter(v=>v.group===3);
assert.equal(g.length,8);
assert.equal(JSON.stringify(g.map(v=>v.pt)),JSON.stringify(routes));
const i=entries.find(v=>v.pt==='bifurcar-se');
assert.ok(lab.focus(i.topic,i.pt));
let html=lab.render();
assert.match(html,/class="vl-diagram" role="img" aria-label="Diagrama do verbo bifurcar-se"/);
assert.match(html,/class="vl-mini-diagram" aria-hidden="true"/);
assert.equal((html.match(/class="vl-mini-diagram"/g)||[]).length,9,'8 miniaturas do campo e 1 contraste ilustrado');
assert.ok(!html.includes('Esquema simplificado: Percurso e travessia'),'detalhe não herda diagrama genérico');
for(const word of routes){
 const v=g.find(x=>x.pt===word);
 lab.focus(v.topic,word);html=lab.render();
 assert.ok(html.includes('Diagrama do verbo '+word),'o desenho acompanha o verbete '+word);
}
const inherited=entries.find(v=>v.pt==='ladear');
lab.focus(inherited.topic,inherited.pt);html=lab.render();
assert.match(html,/Esquema simplificado: Lateralidade e vizinhança/,'outros campos ainda usam fallback seguro');
assert.equal((html.match(/class="vl-mini-diagram"/g)||[]).length,0,'catálogo básico não desenha grupos que ainda não foram carregados');
const css=read('style.css');
assert.match(css,/\.vl-item-illustrated/);
assert.match(css,/\.vl-mini-diagram/);
assert.match(css,/@media\(max-width:720px\)/);
const index=read('index.html');
assert.ok(index.indexOf('spatial-verb-icons.js')<index.indexOf('spatial-verbs.js'),'ícones carregados antes do laboratório');
console.log('Pictogramas: oito SVGs distintos, mini + detalhe, acessibilidade, fallback e 717 verbetes preservados — OK');