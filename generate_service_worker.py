#!/usr/bin/env python3
"""Generate the offline-first service worker with a content-derived cache revision.

No build dependencies. Run: python generate_service_worker.py
Check only: python generate_service_worker.py --check
"""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parent
FILES = [
    'index.html', 'style.css', 'app.js', 'data.js',
    'atlas-data.js', 'urbanism-concepts.js', 'urbanism-lexicon.js',
    'urbanism-atlas.js', 'spatial-verbs-data.js', 'spatial-regency-data.js', 'spatial-verbs.js',
    'atlas-engine.js', 'atlas-recorder.js',
    'atlas-audio-ui.js', 'interact.js', 'manifest.webmanifest',
    'assets/icon.svg', 'assets/skyline.svg'
]
TARGET = ROOT / 'service-worker.js'

def version():
    # FNV-1a over paths and UTF-8 bytes: deterministic content fingerprint.
    h = 2166136261
    for name in FILES:
        for byte in name.encode('utf-8') + b'\0' + (ROOT / name).read_bytes():
            h = ((h ^ byte) * 16777619) & 0xffffffff
    return format(h, '08x')

def render():
    files = "['./','./index.html'," + ','.join("'./" + name + "'" for name in FILES if name != 'index.html') + ']'
    return """/* Generated by generate_service_worker.py; do not edit directly. */
const CACHE = 'storylab-static-__HASH__';
const SHELL = __FILES__;
const OFFLINE_PAGE = './index.html';

self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(SHELL))
    .then(() => self.skipWaiting()));
});
self.addEventListener('activate', event => {
  event.waitUntil(caches.keys().then(keys => Promise.all(
    keys.filter(key => key.startsWith('storylab-static-') && key !== CACHE)
      .map(key => caches.delete(key))
  )).then(() => self.clients.claim()));
});
self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).then(response => {
        if (response.ok && new URL(request.url).pathname === new URL(OFFLINE_PAGE, self.registration.scope).pathname) {
          const copy = response.clone();
          event.waitUntil(caches.open(CACHE).then(cache => cache.put(OFFLINE_PAGE, copy)));
        }
        return response;
      }).catch(async () => (await caches.match(OFFLINE_PAGE)) || Response.error())
    );
    return;
  }
  event.respondWith(
    caches.match(request).then(cached => cached || fetch(request).then(response => {
      if (response.ok && response.type === 'basic') {
        const copy = response.clone();
        event.waitUntil(caches.open(CACHE).then(cache => cache.put(request, copy)));
      }
      return response;
    }))
  );
});
""".replace('__HASH__', version()).replace('__FILES__', files)

def main():
    p = argparse.ArgumentParser()
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    output = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding='utf-8') != output:
            raise SystemExit('Service worker desatualizado: execute python generate_service_worker.py')
        print('Service worker sincronizado com os arquivos estáticos.')
    else:
        TARGET.write_text(output, encoding='utf-8')
        print('Service worker atualizado para', version())

if __name__ == '__main__':
    main()
